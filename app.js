function setLanguage(lang) {
    if (lang !== "ar" && lang !== "en") {
        lang = "ar";
    }

    localStorage.setItem("pc_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

    if (document.body) {
        document.body.dir = lang === "ar" ? "rtl" : "ltr";
    }

    const langBtn = document.getElementById("langBtn");
    if (langBtn) {
        langBtn.innerHTML = lang === "ar" ? "English" : "العربية";
    }

    const dictionary = translations[lang];
    if (!dictionary) return;

    document.querySelectorAll("[data-i18n]").forEach(function (element) {
        const key = element.getAttribute("data-i18n");
        if (key && Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.innerHTML = dictionary[key];
        }
    });

    document.querySelectorAll("[data-i18n-ph]").forEach(function (element) {
        const key = element.getAttribute("data-i18n-ph");
        if (key && Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.placeholder = dictionary[key];
        }
    });

    const titleElement = document.querySelector("title[data-i18n]");
    if (titleElement) {
        const key = titleElement.getAttribute("data-i18n");
        if (key && Object.prototype.hasOwnProperty.call(dictionary, key)) {
            document.title = dictionary[key];
        }
    }
}

function toggleLanguage() {
    const currentLang = localStorage.getItem("pc_lang") || "ar";
    const newLang = currentLang === "ar" ? "en" : "ar";
    setLanguage(newLang);
}

function setTheme(theme) {
    if (theme !== "light" && theme !== "dark") {
        theme = "dark";
    }

    localStorage.setItem("pc_theme", theme);
    document.body.classList.remove("light-theme", "dark-theme");
    document.body.classList.add(theme === "light" ? "light-theme" : "dark-theme");
    document.documentElement.setAttribute("data-theme", theme);

    const themeBtn = document.getElementById("themeBtn");
    if (themeBtn) {
        themeBtn.innerHTML = theme === "light" ? "Dark" : "Light";
    }
}

function toggleTheme() {
    const currentTheme = localStorage.getItem("pc_theme") || "dark";
    const newTheme = currentTheme === "dark" ? "light" : "dark";
    setTheme(newTheme);
}

function initializeApp() {
    const savedLang = localStorage.getItem("pc_lang") || "ar";
    const savedTheme = localStorage.getItem("pc_theme") || "dark";

    setLanguage(savedLang);
    setTheme(savedTheme);
}

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initializeApp);
} else {
    initializeApp();
}

window.setLanguage = setLanguage;
window.toggleLanguage = toggleLanguage;
window.setTheme = setTheme;
window.toggleTheme = toggleTheme;

